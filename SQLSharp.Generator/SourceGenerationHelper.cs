    public static string GenerateWrapperDecode(
        WrapperTypeToGenerate wrapperTypeToGenerate,
        SourceProductionContext sourceProductionContext)
    {
        if (!wrapperTypeToGenerate.IsPartial)
        {
            sourceProductionContext.ReportDiagnostic(
                Diagnostic.Create(
                    TypeIsNotPartial,
                    Location.None,
                    wrapperTypeToGenerate.Name));
            return string.Empty;
        }

        if (wrapperTypeToGenerate.InnerValue is null)
        {
            sourceProductionContext.ReportDiagnostic(
                Diagnostic.Create(
                    TypeInvalidWrapperType,
                    Location.None,
                    wrapperTypeToGenerate.Name));
            return string.Empty;
        }
        
        var type = wrapperTypeToGenerate.IsStruct ? "struct" : "class";
        var typeNamespace = string.IsNullOrWhiteSpace(wrapperTypeToGenerate.Namespace)
            ? string.Empty
            : $"{wrapperTypeToGenerate.Namespace}.";
        var innerValueDbType = GetDbType(wrapperTypeToGenerate.InnerValue.TypeName);
        var parameterTypeAssignment = innerValueDbType is null
            ? string.Empty
            : $"parameter.DbType = System.Data.DbType.{innerValueDbType};\n        ";
        var initialization = wrapperTypeToGenerate.HasNonDefaultConstructor
            ? $"return new {wrapperTypeToGenerate.Name}(row.GetField<{wrapperTypeToGenerate.InnerValue.TypeName}>(column));"
            : $$"""
                return new {{wrapperTypeToGenerate.Name}}
                        {
                            {{wrapperTypeToGenerate.InnerValue.Name}} = row.GetField<{{wrapperTypeToGenerate.InnerValue.TypeName}}>(column)
                        };
                """;
        return
            $$"""
              // <auto-generated/>
              #nullable enable

              partial {{type}} {{typeNamespace}}{{wrapperTypeToGenerate.Name}} : SQLSharp.Types.IDbDecode<{{typeNamespace}}{{wrapperTypeToGenerate.Name}}>, SQLSharp.Types.IDbEncode
              {
                  public void Encode(ref System.Data.IDbDataParameter parameter)
                  {
                      {{parameterTypeAssignment}}parameter.Value = {{wrapperTypeToGenerate.InnerValue.Name}};
                  }
              
                  public static {{typeNamespace}}{{wrapperTypeToGenerate.Name}} Decode(SQLSharp.Result.IDataRow row, int column)
                  {
                      {{initialization}}
                  }
              }
              """;
    }

    public static string? GetDbType(string parameter)
    {
        return parameter switch
        {
            "System.Boolean" => "Boolean",
            "System.Byte" => "SByte",
            "System.Int16" => "Int16",
            "System.UInt16" => "UInt16",
            "System.Int32" => "Int32",
            "System.UInt32" => "UInt32",
            "System.Int64" => "Int64",
            "System.UInt64" => "UInt64",
            "System.Byte[]" => "Binary",
            "System.Char" => "String",
            "System.Char[]" => "String",
            "System.String" => "String",
            "System.Decimal" => "Decimal",
            "System.Single" => "Single",
            "System.Double" => "Double",
            "System.DateTime" => "DateTime",
            "System.DateTimeOffset" => "DateTimeOffset",
            "System.Guid" => "Guid",
            _ => null,
        };
    }
}
