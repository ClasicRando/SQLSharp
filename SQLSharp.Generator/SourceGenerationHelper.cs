public static class SourceGenerationHelper
{
    private static readonly DiagnosticDescriptor TypeIsNotPartial =
        new(
            "SQLSHARP001",
            "Annotated type is not partial",
            "'{0}' must be partial to allow for adding extra behaviour",
            "SQLSharp Generation",
            DiagnosticSeverity.Error,
            true);
    private static readonly DiagnosticDescriptor TypeInvalidWrapperType =
        new(
            "SQLSHARP002",
            "Annotated type is not a valid wrapper type",
            "'{0}' must have exactly 1 field or property to be a wrapper type",
            "SQLSharp Generation",
            DiagnosticSeverity.Error,
            true);

